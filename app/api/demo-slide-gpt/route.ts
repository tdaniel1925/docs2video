import { NextResponse } from 'next/server'
import { createClient } from '../../_lib/supabase/server'
import { CREDIT_COSTS } from '../../_lib/credits'
import { runCharged } from '../../_lib/credit-charge'
import { rateLimit, getRateLimitKey, LIMITS } from '../../_lib/rate-limit'
import { isAdminRequest } from '../../_lib/admin'
import { falImagePng } from '../../_lib/fal-image'
import { GoogleGenAI } from '@google/genai'

export const runtime = 'nodejs'
export const maxDuration = 300

export async function POST(request: Request) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Not authenticated' }, { status: 401 })
  // Internal demo tool (/demo-slide is admin-only) — any signed-in user could
  // previously call this and spend credits on it (audit 2026-09-26).
  if (!(await isAdminRequest(user))) return NextResponse.json({ error: 'Forbidden' }, { status: 403 })

  const rl = rateLimit(getRateLimitKey(user.id, 'demo-slide'), LIMITS.generation.limit, LIMITS.generation.windowMs)
  if (!rl.allowed) {
    return NextResponse.json({ error: 'Rate limit exceeded. Please wait a bit before generating again.' }, { status: 429 })
  }

  const { logoImage, prompt, companyName, provider = 'openai' } = await request.json() as {
    logoImage?: string
    prompt: string
    companyName?: string
    provider?: 'openai' | 'gemini'
  }

  if (!prompt) return NextResponse.json({ error: 'Prompt required' }, { status: 400 })
  if (provider !== 'openai' && provider !== 'gemini') {
    return NextResponse.json({ error: 'Invalid provider' }, { status: 400 })
  }

  // Charge once the request is valid; an empty or failed generation gives the
  // credits back (audit H5).
  return runCharged({ userId: user.id, amount: CREDIT_COSTS['demo-slide'], action: 'demo-slide' }, async () => {
  try {
    // ── OPENAI gpt-image-2.5, on fal (fal-image.ts; OpenAI direct until 2026-10-19)
    if (provider === 'openai') {
      const fullPrompt = logoImage
        ? (companyName ? `Take this logo for "${companyName}" and ${prompt}` : `Take this logo and ${prompt}`)
        : prompt
      const logo = logoImage?.match(/^data:image\/\w+;base64,(.+)$/)?.[1]
      console.log(`[demo] generating with gpt-image-2.5 on fal...`)
      const png = await falImagePng(fullPrompt, {
        width: 1536, height: 1024, quality: 'medium',
        images: logo ? [Buffer.from(logo, 'base64')] : [],
      })
      return NextResponse.json({ image: `data:image/png;base64,${png.toString('base64')}` })
    }

    // ── GEMINI ──────────────────────────────────────────────
    if (provider === 'gemini') {
      const genai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY! })

      const fullPrompt = companyName
        ? `${prompt}\n\nCompany: "${companyName}"`
        : prompt

      const parts: any[] = [{ text: fullPrompt }]
      if (logoImage) {
        const match = logoImage.match(/^data:(image\/\w+);base64,(.+)$/)
        if (match) {
          parts.push({ inlineData: { mimeType: match[1], data: match[2] } })
        }
      }

      console.log(`[demo] Gemini generating (gemini-3-pro-image-preview)...`)

      const response = await genai.models.generateContent({
        model: 'gemini-3-pro-image-preview',
        contents: [{ role: 'user', parts }],
        config: { responseFormat: { image: { aspectRatio: '16:9', imageSize: '4K' } } } as any,
      })

      const responseParts = response.candidates?.[0]?.content?.parts ?? []
      for (const rp of responseParts) {
        if (rp.inlineData) {
          return NextResponse.json({ image: `data:image/png;base64,${rp.inlineData.data}` })
        }
      }

      return NextResponse.json({ error: 'No image generated by Gemini' }, { status: 500 })
    }

    return NextResponse.json({ error: 'Invalid provider' }, { status: 400 })
  } catch (err: any) {
    // Public endpoint: log the real (possibly upstream/Gemini) error server-side,
    // return a generic message so no internals leak to the caller.
    console.error(`[demo] ${provider} error:`, err)
    return NextResponse.json({ error: 'Generation failed' }, { status: 500 })
  }
  })
}
